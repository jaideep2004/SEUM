export const dictionaries: Record<Lang, Record<string, string>> = { en, ar };

/** Dot-key lookup with English fallback, then the key itself. Never throws. */
export function translate(lang: Lang, key: string): string {
  return dictionaries[lang][key] ?? dictionaries.en[key] ?? key;
}

/** Sidebar section label — falls back to the English label from access.ts. */
export function navSectionLabel(sectionKey: string, fallback: string, lang: Lang): string {
  if (lang === "en") return fallback;
  return dictionaries.ar[`nav.sections.${sectionKey}`] ?? fallback;
}

/** Sidebar item label — keyed by href so access.ts needs no changes. */
export function navItemLabel(href: string, fallback: string, lang: Lang): string {
  if (lang === "en") return fallback;
  return dictionaries.ar[`nav.items.${href}`] ?? fallback;
}

/** Localized role display name. */
export function localizedRoleLabel(role: string, lang: Lang): string {
  if (lang === "en") return role;
  return dictionaries.ar[`roles.${role}`] ?? role;
}
